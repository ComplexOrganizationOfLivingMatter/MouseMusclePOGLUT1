import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
from skimage import io, measure

# ============================================================
# CONFIGURATION & CONSTANTS
# ============================================================
BASE_DIR = Path("../../")
RESULT_DIR = BASE_DIR / "results" / "largeModel_dotDetection"
VOR_ROOT = RESULT_DIR / "voronoiImages"
MASK_ROOT = BASE_DIR / "data" / "annotatedMuscleMasks"

UM_PER_PIXEL = 0.5055443
PIXEL_AREA_UM2 = UM_PER_PIXEL**2
BONE_ZONE = 6
EXCLUDED_ZONES = {0, BONE_ZONE, 13, 1} # Exclude G1 and others

# Set plotting style & consistent colors/order
sns.set_theme(style="whitegrid")
plt.rcParams.update({'font.sans-serif': 'Arial', 'font.size': 11})

GENOTYPE_ORDER = ["WT", "KIKO"]
GENOTYPE_BOX_PALETTE = {"WT": "#a6c8e0", "KIKO": "#fba375"}
GENOTYPE_DOT_PALETTE = {"WT": "#1a426e", "KIKO": "#b33d00"}

AGE_SAMPLE_PERCENTAGE_THRESHOLD = 0.20


def load_latest_excel_report(result_dir: Path) -> pd.DataFrame:
    """Finds and loads the most recent Excel report generated by the pipeline."""
    excel_files = sorted(result_dir.glob("Pax7_DotDetection_Analysis_*.xlsx"))
    if not excel_files:
        raise FileNotFoundError(f"No analysis Excel report found in {result_dir}")
    latest_file = excel_files[-1]
    print(f"[INFO] Loading data from: {latest_file.name}")
    return pd.read_excel(latest_file, sheet_name="Raw_Data")


# ============================================================
# OUTLIER FILTERING HELPER (Mean ± 2*SD)
# ============================================================
def filter_outliers_2std(df: pd.DataFrame, value_col: str) -> pd.DataFrame:
    """
    Removes data points further than 2 standard deviations from the mean 
    for each combination of age, genotype, and muscle_group.
    """
    filtered_groups = []
    group_cols = ["age", "genotype", "muscle_group"]
    
    for _, group in df.groupby(group_cols):
        mean_val = group[value_col].mean()
        std_val = group[value_col].std()
        
        if pd.isna(std_val) or std_val == 0:
            filtered_groups.append(group)
        else:
            lower_bound = mean_val - 2 * std_val
            upper_bound = mean_val + 2 * std_val
            clean_group = group[(group[value_col] >= lower_bound) & (group[value_col] <= upper_bound)]
            filtered_groups.append(clean_group)
            
    return pd.concat(filtered_groups, ignore_index=True)


# ============================================================
# EXTRACT PER-ZONE VORONOI CELL METRICS (MEAN & SD)
# ============================================================
def compute_per_zone_voronoi_stats(df_raw: pd.DataFrame, mask_root: Path, vor_root: Path) -> pd.DataFrame:
    """
    Computes the mean and standard deviation of Voronoi cell areas (um2) 
    for each individual muscle zone across images.
    """
    print("\n[STAGE] Computing per-zone Voronoi cell area statistics...")
    records = []

    for _, row in df_raw.iterrows():
        img_name = row["image"]
        age = str(row["age"]).strip()
        genotype = row["genotype"]

        vor_path = vor_root / age / img_name
        mask_path = mask_root / age / img_name
        if not vor_path.exists() or not mask_path.exists():
            found_vor = list(vor_root.rglob(img_name))
            found_mask = list(mask_root.rglob(img_name))
            if not found_vor or not found_mask:
                continue
            vor_path = found_vor[0]
            mask_path = found_mask[0]

        try:
            voronoi_img = io.imread(str(vor_path)).astype(np.uint32)
            mask_zones = io.imread(str(mask_path))
            mask_zones = mask_zones[..., 0] if mask_zones.ndim == 3 else mask_zones

            props = measure.regionprops(voronoi_img)
            if not props:
                continue

            zone_to_areas = {}
            for p in props:
                cy, cx = map(int, p.centroid)
                if 0 <= cy < mask_zones.shape[0] and 0 <= cx < mask_zones.shape[1]:
                    z_id = mask_zones[cy, cx]
                    if z_id not in EXCLUDED_ZONES:
                        area_um2 = p.area * PIXEL_AREA_UM2
                        zone_to_areas.setdefault(z_id, []).append(area_um2)

            for z_id, areas in zone_to_areas.items():
                if len(areas) > 0:
                    records.append({
                        "image": img_name,
                        "age": age,
                        "genotype": genotype,
                        "muscle_group": f"G{z_id}",
                        "mean_voronoi_area": np.mean(areas),
                        "std_voronoi_area": np.std(areas) if len(areas) > 1 else 0.0
                    })
        except Exception as e:
            continue

    return pd.DataFrame(records)


# ============================================================
# PLOTTING HELPER WITH ORGANIZED DIRECTORIES
# ============================================================
def generate_metric_plots(melted_df: pd.DataFrame, metric_col: str, metric_label: str, subfolder_name: str):
    """
    Generates shared and independent Y-axis plots for a given metric 
    after filtering out values outside Mean ± 2*SD.
    """
    print(f"\n[STAGE] Generating {metric_label} plots (Outliers > 2*SD removed)...")
    
    # Apply 2*SD Outlier Filter per condition
    filtered_df = filter_outliers_2std(melted_df, metric_col)

    global_max = filtered_df[metric_col].max()
    if np.isnan(global_max) or global_max == 0:
        global_max = 1.0
    shared_y_limit = global_max * 1.15

    base_plot_dir = RESULT_DIR / "plots_density_by_age" / subfolder_name
    shared_dir = base_plot_dir / "shared_yaxis"
    independent_dir = base_plot_dir / "independent_yaxis"
    
    shared_dir.mkdir(parents=True, exist_ok=True)
    independent_dir.mkdir(parents=True, exist_ok=True)

    ages = filtered_df["age"].unique()

    for age in ages:
        df_age = filtered_df[filtered_df["age"] == age].copy()
        if df_age.empty:
            continue

        total_samples = df_age["image"].nunique()
        group_counts = df_age.dropna(subset=[metric_col]).groupby("muscle_group")["image"].nunique()
        
        valid_groups = [
            grp for grp, count in group_counts.items()
            if (count / total_samples) >= AGE_SAMPLE_PERCENTAGE_THRESHOLD
        ]

        df_age_filtered = df_age[df_age["muscle_group"].isin(valid_groups)]
        if df_age_filtered.empty:
            continue

        present_genotypes = [g for g in GENOTYPE_ORDER if g in df_age_filtered["genotype"].unique()]
        safe_age = str(age).replace(" ", "_").replace("/", "_")

        # --- VARIANT A: SHARED Y-AXIS ---
        try:
            plt.figure(figsize=(14, 6))
            sns.boxplot(
                data=df_age_filtered, x="muscle_group", y=metric_col, hue="genotype",
                hue_order=GENOTYPE_ORDER, palette=GENOTYPE_BOX_PALETTE, boxprops=dict(alpha=0.6), 
                showcaps=True, showfliers=False
            )
            sns.stripplot(
                data=df_age_filtered, x="muscle_group", y=metric_col, hue="genotype",
                hue_order=GENOTYPE_ORDER, palette=GENOTYPE_DOT_PALETTE, dodge=True, jitter=0.2, size=6, linewidth=0.8, edgecolor="black"
            )
            plt.ylim(0, shared_y_limit)
            plt.title(f"{metric_label} per Muscle Group (Shared Scale, Mean±2SD Filtered) — Age: {age}", fontsize=14, fontweight="bold", pad=15)
            plt.xlabel("Muscle Group", fontweight="bold")
            plt.ylabel(metric_label, fontweight="bold")
            
            handles, labels = plt.gca().get_legend_handles_labels()
            if handles:
                by_label = dict(zip(labels[:len(present_genotypes)], handles[:len(present_genotypes)]))
                plt.legend(by_label.values(), by_label.keys(), title="Genotype", frameon=True)

            plt.tight_layout()
            plt.savefig(shared_dir / f"{subfolder_name}_{safe_age}_shared.png", dpi=300)
            plt.close()
        except Exception as e:
            plt.close()

        # --- VARIANT B: INDEPENDENT Y-AXIS ---
        try:
            plt.figure(figsize=(14, 6))
            sns.boxplot(
                data=df_age_filtered, x="muscle_group", y=metric_col, hue="genotype",
                hue_order=GENOTYPE_ORDER, palette=GENOTYPE_BOX_PALETTE, boxprops=dict(alpha=0.6), 
                showcaps=True, showfliers=False
            )
            sns.stripplot(
                data=df_age_filtered, x="muscle_group", y=metric_col, hue="genotype",
                hue_order=GENOTYPE_ORDER, palette=GENOTYPE_DOT_PALETTE, dodge=True, jitter=0.2, size=6, linewidth=0.8, edgecolor="black"
            )
            
            age_max = df_age_filtered[metric_col].max()
            if not np.isnan(age_max) and age_max > 0:
                plt.ylim(0, age_max * 1.15)

            plt.title(f"{metric_label} per Muscle Group (Independent Scale, Mean±2SD Filtered) — Age: {age}", fontsize=14, fontweight="bold", pad=15)
            plt.xlabel("Muscle Group", fontweight="bold")
            plt.ylabel(metric_label, fontweight="bold")
            
            handles, labels = plt.gca().get_legend_handles_labels()
            if handles:
                by_label = dict(zip(labels[:len(present_genotypes)], handles[:len(present_genotypes)]))
                plt.legend(by_label.values(), by_label.keys(), title="Genotype", frameon=True)

            plt.tight_layout()
            plt.savefig(independent_dir / f"{subfolder_name}_{safe_age}_independent.png", dpi=300)
            plt.close()
        except Exception as e:
            plt.close()


