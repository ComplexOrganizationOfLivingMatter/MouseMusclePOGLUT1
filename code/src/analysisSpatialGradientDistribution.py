"""
Pax7 Spatial Gradient, Radial Rings & Bone-Centered Dorso-Ventral Analysis
Memory-Optimized & Density-Normalized for Pedro's Muscle Regeneration Pipeline
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from pathlib import Path
from skimage import io, measure
from scipy.ndimage import distance_transform_edt, map_coordinates

# ============================================================
# CONFIGURATION & CONSTANTS
# ============================================================
BASE_DIR = Path("../../")
RESULT_DIR = BASE_DIR / "results" / "largeModel_dotDetection"
MASK_ROOT = BASE_DIR / "data" / "annotatedMuscleMasks"
VOR_ROOT = RESULT_DIR / "voronoiImages"

BONE_ZONE = 6
UM_PER_PIXEL = 0.5055443
PIXEL_AREA_UM2 = UM_PER_PIXEL**2

# Bin size configurations (in microns) - Wider bins (200 µm)
RADIAL_BIN_UM = 200       # Radial rings width outwards from bone
DV_STRIPE_BIN_UM = 200    # DV parallel stripes width from ventral to dorsal

# Set plotting style
sns.set_theme(style="whitegrid")
plt.rcParams.update({'font.sans-serif': 'Arial', 'font.size': 11})


def load_latest_excel_report(result_dir: Path) -> pd.DataFrame:
    """Finds and loads the most recent Excel report generated by the pipeline."""
    excel_files = sorted(result_dir.glob("Pax7_DotDetection_Analysis_*.xlsx"))
    if not excel_files:
        raise FileNotFoundError(f"No analysis Excel report found in {result_dir}")
    latest_file = excel_files[-1]
    print(f"[INFO] Loading data from: {latest_file.name}")
    return pd.read_excel(latest_file, sheet_name="Raw_Data")


# ============================================================
# MEMORY-OPTIMIZED SPATIAL & DENSITY ANALYSIS FUNCTION
# ============================================================
def analyze_spatial_distributions(df: pd.DataFrame, mask_root: Path, vor_root: Path, output_dir: Path):
    """
    Computes spatial distributions, muscle geometry, and true mask-restricted densities 
    (Pax7 count / muscle area in µm²) for radial rings and bone-centered DV stripes.
    """
    print("\n[STAGE] Analyzing Radial Rings, Bone-Centered DV Axes, and Mask-Restricted Densities...")
    
    density_ring_records = []
    density_vector_records = []
    geometry_records = []

    # Directories for debug maps and plots
    debug_dir = output_dir / "spatial_debug_visualizations"
    debug_dir.mkdir(parents=True, exist_ok=True)

    plot_dir = output_dir / "plots_spatial_organization"
    plot_dir.mkdir(parents=True, exist_ok=True)

    for _, row in df.iterrows():
        img_name = row["image"]
        age = str(row["age"]).strip()
        genotype = row["genotype"]

        # Find corresponding mask and voronoi files
        mask_path = mask_root / age / img_name
        if not mask_path.exists():
            found = list(mask_root.rglob(img_name))
            if not found:
                continue
            mask_path = found[0]

        vor_path = vor_root / age / img_name
        if not vor_path.exists():
            continue

        try:
            # Load anatomical annotation mask (zones) and Voronoi/nuclear detection map
            mask_zones = io.imread(str(mask_path))
            mask_zones = mask_zones[..., 0] if mask_zones.ndim == 3 else mask_zones
            
            voronoi_img = io.imread(str(vor_path)).astype(np.uint32)
            props = measure.regionprops(voronoi_img)
            if not props:
                continue

            # ========================================================
            # 1. BONE & LANDMARK LOCALIZATION
            # ========================================================
            # Locate Bone (Zone 6) and compute its centroid as the origin (0.0 µm)
            bone_mask = (mask_zones == BONE_ZONE)
            if not np.any(bone_mask):
                continue
            bone_coords = np.argwhere(bone_mask)
            bone_centroid = bone_coords.mean(axis=0) # [y, x]

            # Define full muscle tissue mask (all zones > 0)
            muscle_mask = (mask_zones > 0)
            muscle_coords = np.argwhere(muscle_mask)
            if len(muscle_coords) == 0:
                continue

            # Calculate muscle geometry (major and minor axes)
            muscle_props = measure.regionprops(measure.label(muscle_mask))
            if muscle_props:
                main_muscle = max(muscle_props, key=lambda r: r.area)
                major_axis_um = main_muscle.major_axis_length * UM_PER_PIXEL
                minor_axis_um = main_muscle.minor_axis_length * UM_PER_PIXEL
            else:
                major_axis_um, minor_axis_um = np.nan, np.nan

            # Locate Dorsal (Group 5) & Ventral (Groups 8, 9, 10) Landmarks
            g5_mask = (mask_zones == 5)
            ventral_mask = np.isin(mask_zones, [8, 9, 10])

            if not np.any(g5_mask) or not np.any(ventral_mask):
                continue

            g5_centroid = np.argwhere(g5_mask).mean(axis=0)
            ventral_centroid = np.argwhere(ventral_mask).mean(axis=0)

            # ========================================================
            # 2. DORSO-VENTRAL (DV) AXIS VECTOR & PROJECTIONS
            # ========================================================
            # Establish DV unit vector pointing from Ventral -> Dorsal 
            # (so Dorsal is positive +, Ventral is negative -, and Bone is 0.0)
            dv_vector = g5_centroid - ventral_centroid
            dv_length = np.linalg.norm(dv_vector)
            if dv_length == 0:
                continue
            dv_unit = dv_vector / dv_length

            # Project all muscle pixels onto DV axis relative to BONE centroid (= 0)
            muscle_dv_projections = np.dot(muscle_coords - bone_centroid, dv_unit)
            dorsal_bg_edge_bone = np.max(muscle_dv_projections)  # Dorsal background edge (+ distance)
            ventral_bg_edge_bone = np.min(muscle_dv_projections) # Ventral background edge (- distance)

            dorsal_span = dorsal_bg_edge_bone  
            ventral_span = abs(ventral_bg_edge_bone) 

            if dorsal_span == 0 or ventral_span == 0:
                continue

            total_dv_length_um = (dorsal_span + ventral_span) * UM_PER_PIXEL

            geometry_records.append({
                "image": img_name,
                "age": age,
                "genotype": genotype,
                "dv_total_length_um": total_dv_length_um,
                "minor_axis_um": minor_axis_um,
                "major_axis_um": major_axis_um,
                "dorsal_span_um": dorsal_span * UM_PER_PIXEL,
                "ventral_span_um": ventral_span * UM_PER_PIXEL
            })

            # ========================================================
            # 3. DISTANCE TRANSFORMS & AREA RESTRICTIONS
            # ========================================================
            n_poss = np.array([p.centroid for p in props]) # Shape: (N_nuclei, 2) [y, x]

            # A. Radial Ring Distance Map from Bone (~bone_mask inverted for edt)
            bone_dist_map = distance_transform_edt(~bone_mask) * UM_PER_PIXEL
            distances_to_bone = map_coordinates(bone_dist_map, [n_poss[:, 0], n_poss[:, 1]], order=1, mode='nearest')

            # Calculate exact muscle area (µm²) falling into each radial ring bin (excluding non-mask regions)
            muscle_bone_dists = bone_dist_map[muscle_mask]
            muscle_ring_bins = (muscle_bone_dists // RADIAL_BIN_UM) * RADIAL_BIN_UM
            unique_rings, ring_pixel_counts = np.unique(muscle_ring_bins, return_counts=True)
            ring_area_dict = {r: c * PIXEL_AREA_UM2 for r, c in zip(unique_rings, ring_pixel_counts)}

            # B. DV Stripe Distance Map from Bone
            muscle_dv_projections_um = np.dot(muscle_coords - bone_centroid, dv_unit) * UM_PER_PIXEL
            muscle_stripe_bins = (muscle_dv_projections_um // DV_STRIPE_BIN_UM) * DV_STRIPE_BIN_UM
            unique_stripes, stripe_pixel_counts = np.unique(muscle_stripe_bins, return_counts=True)
            stripe_area_dict = {s: c * PIXEL_AREA_UM2 for s, c in zip(unique_stripes, stripe_pixel_counts)}

            # Nuclei DV projections & normalized scores (-1 to +1)
            dv_bone_projections_px = np.dot(n_poss - bone_centroid, dv_unit)
            dv_bone_projections_um = dv_bone_projections_px * UM_PER_PIXEL

            # ========================================================
            # 4. AGGREGATE COUNTS & DENSITY CALCULATION (Pax7 / µm²)
            # ========================================================
            image_ring_counts = {}
            for dist in distances_to_bone:
                r_bin = int(dist // RADIAL_BIN_UM) * RADIAL_BIN_UM
                image_ring_counts[r_bin] = image_ring_counts.get(r_bin, 0) + 1

            image_stripe_counts = {}
            for dv_um in dv_bone_projections_um:
                s_bin = int(dv_um // DV_STRIPE_BIN_UM) * DV_STRIPE_BIN_UM
                image_stripe_counts[s_bin] = image_stripe_counts.get(s_bin, 0) + 1

            # Compute Density for Rings
            for r_bin, count in image_ring_counts.items():
                mask_area = ring_area_dict.get(r_bin, 0)
                if mask_area > 0:
                    density_val = count / mask_area
                    density_ring_records.append({
                        "image": img_name,
                        "age": age,
                        "genotype": genotype,
                        "ring_bin_um": f"{r_bin}-{r_bin+RADIAL_BIN_UM} µm",
                        "ring_order": r_bin,
                        "pax7_density_um2": density_val
                    })

            # Compute Density for DV Stripes
            for s_bin, count in image_stripe_counts.items():
                mask_area = stripe_area_dict.get(s_bin, 0)
                if mask_area > 0:
                    density_val = count / mask_area
                    density_vector_records.append({
                        "image": img_name,
                        "age": age,
                        "genotype": genotype,
                        "dv_stripe_um": f"{s_bin}-{s_bin+DV_STRIPE_BIN_UM} µm",
                        "dv_stripe_order": s_bin,
                        "pax7_density_um2": density_val
                    })

            # ========================================================
            # 5. DEBUG VISUALIZATION MAPS FOR EVERY MUSCLE (~500x500)
            # ========================================================
            # Generates and saves an overlay image showing the bone, landmarks, and DV axis vector
            fig, ax = plt.subplots(figsize=(6, 6))
            ax.imshow(mask_zones, cmap="tab20", alpha=0.6)
            ax.scatter(bone_centroid[1], bone_centroid[0], color='red', s=50, label="Bone (0)")
            ax.scatter(g5_centroid[1], g5_centroid[0], color='blue', s=30, label="Dorsal (G5)")
            ax.scatter(ventral_centroid[1], ventral_centroid[0], color='green', s=30, label="Ventral (8,9,10)")
            
            dorsal_tip = bone_centroid + dv_unit * dorsal_span
            ventral_tip = bone_centroid - dv_unit * ventral_span
            ax.plot([ventral_tip[1], dorsal_tip[1]], [ventral_tip[0], dorsal_tip[0]], 'k--', lw=2, label="DV Axis")
            
            ax.set_title(f"{img_name}\n({age} - {genotype})", fontsize=9)
            ax.axis('off')
            ax.legend(loc='upper right', fontsize=8)
            
            clean_stem = Path(img_name).stem.replace(" ", "_")
            fig.savefig(debug_dir / f"debug_spatial_{clean_stem}.png", dpi=80, bbox_inches='tight')
            plt.close(fig)

        except Exception as e:
            print(f"[ERROR] Processing spatial gradients for {img_name}: {e}")
            continue

    df_rings = pd.DataFrame(density_ring_records)
    df_vector = pd.DataFrame(density_vector_records)
    df_geom = pd.DataFrame(geometry_records)

    if not df_geom.empty:
        df_geom.to_excel(output_dir / "muscle_geometry_summary.xlsx", index=False)
        print(f"  -> Muscle geometry summary saved to: {output_dir / 'muscle_geometry_summary.xlsx'}")

    # ========================================================
    # PLOTTING: DENSITY WITH INDIVIDUAL SAMPLE LINES & SD SHADING
    # ========================================================
    print("[STAGE] Generating Density Line Plots with Individual Sample Support & SD Shading...")

    # 1. Radial Ring Densities from Bone
    if not df_rings.empty:
        for age in df_rings["age"].unique():
            df_age_ring = df_rings[df_rings["age"] == age]
            if df_age_ring.empty:
                continue

            plt.figure(figsize=(10, 6))
            # Individual sample lines (gray, transparent) to show sample support per point
            sns.lineplot(
                data=df_age_ring,
                x="ring_order",
                y="pax7_density_um2",
                units="image",
                estimator=None,
                color="gray",
                alpha=0.25,
                linewidth=1.0,
                label="Individual Muscle Sample"
            )
            # Aggregate mean with shaded standard deviation
            sns.lineplot(
                data=df_age_ring,
                x="ring_order",
                y="pax7_density_um2",
                hue="genotype",
                style="genotype",
                markers=True,
                dashes=False,
                palette={"WT": "#2b5c8f", "KIKO": "#d95f02"},
                errorbar=("sd", 1),
                linewidth=2.5,
                markersize=8
            )
            plt.title(f"Pax7 Radial Density from Bone ({RADIAL_BIN_UM}µm rings) — Age: {age}", fontsize=13, fontweight="bold")
            plt.xlabel("Distance from Bone (µm) [0 = Bone]", fontweight="bold")
            plt.ylabel(r"Pax7 Density ($\mu m^{-2}$)", fontweight="bold")
            plt.legend(title="Legend")
            plt.tight_layout()

            safe_age = str(age).replace(" ", "_")
            plt.savefig(plot_dir / f"radial_rings_density_line_{safe_age}.png", dpi=300)
            plt.close()

    # 2. Bone-Centered DV Absolute Stripe Densities
    if not df_vector.empty:
        for age in df_vector["age"].unique():
            df_age_vec = df_vector[df_vector["age"] == age]
            if df_age_vec.empty:
                continue

            df_age_vec = df_age_vec.sort_values("dv_stripe_order")

            plt.figure(figsize=(12, 6))
            # Individual sample curves for full transparency of sample size/support
            sns.lineplot(
                data=df_age_vec,
                x="dv_stripe_order",
                y="pax7_density_um2",
                units="image",
                estimator=None,
                color="gray",
                alpha=0.25,
                linewidth=1.0,
                label="Individual Muscle Sample"
            )
            # Aggregate mean with SD shading
            sns.lineplot(
                data=df_age_vec,
                x="dv_stripe_order",
                y="pax7_density_um2",
                hue="genotype",
                palette={"WT": "#2b5c8f", "KIKO": "#d95f02"},
                errorbar=("sd", 1),
                linewidth=2.5,
                markers=True
            )
            plt.axvline(0, color='red', linestyle='--', label="Bone Origin (0 µm)")
            plt.title(f"Pax7 Density along Bone-Centered DV Stripes ({DV_STRIPE_BIN_UM}µm) — Age: {age}", fontsize=13, fontweight="bold")
            plt.xlabel("Absolute Distance from Bone along DV Axis (µm) [- Ventral, + Dorsal]", fontweight="bold")
            plt.ylabel(r"Pax7 Density ($\mu m^{-2}$)", fontweight="bold")
            plt.xticks(rotation=45)
            plt.legend(title="Legend")
            plt.tight_layout()

            safe_age = str(age).replace(" ", "_")
            plt.savefig(plot_dir / f"dv_absolute_stripes_density_line_{safe_age}.png", dpi=300)
            plt.close()

    print(f"  -> All density visualizations and line plots successfully saved in: {output_dir}")


